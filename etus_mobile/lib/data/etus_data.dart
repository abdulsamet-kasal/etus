  /// Tek bir hattı kurar; durak adlarını _poiByName ile POI'ya bağlar.
  static RouteLine _line({
    required String id,
    required String title,
    required String description,
    required int colorValue,
    required String interval,
    required String intervalDetail,
    required String scheduleSource,
    required int avgHeadwayMin,
    int? avgTripMinutes,
    String? serviceHours,
    required List<String> stops,
  }) {
    return RouteLine(
      id: id,
      name: 'Hat $id',
      title: title,
      description: description,
      colorValue: colorValue,
      interval: interval,
      intervalDetail: intervalDetail,
      scheduleSource: scheduleSource,
      avgHeadwayMin: avgHeadwayMin,
      avgTripMinutes: avgTripMinutes,
      serviceHours: serviceHours,
      waypoints: [
        for (final s in stops) RouteWaypoint(s, placeId: _poiByName[s]),
      ],
    );
  }

